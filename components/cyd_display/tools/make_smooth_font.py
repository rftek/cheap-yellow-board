"""Generates smooth_font.inc: anti-aliased glyphs for cyd_display's big text cells.

The S3 board's text cells are 30x40 pixels (the 6x8 cell at font scale 5).
Instead of blowing the 5x7 font up five times, cyd_display_common.c draws
these glyphs, rendered from DejaVu Sans Mono Bold with 16 levels of coverage,
so every app's 26x12 text grid stays the same and only the letters change.

Usage (needs Pillow):
    python make_smooth_font.py DejaVuSansMono-Bold.ttf ../smooth_font.inc

DejaVu fonts: https://github.com/dejavu-fonts/dejavu-fonts (version 2.37);
their license is in ../fonts/DejaVu-LICENSE.txt.
"""

import sys

from PIL import Image, ImageDraw, ImageFont

CELL_W = 30
CELL_H = 40
# The cell's last row stays black (it separates text rows), so glyphs get 39.
GLYPH_H = CELL_H - 1
# The largest size whose tallest glyphs (brackets, |) fit 39 rows; glyphs
# are then widened by STRETCH to fill the cell, leaving about the old
# font's 5-pixel gap between letters.
FONT_PX = 37
STRETCH = 1.15
SUPERSAMPLE = 4


def coverage_rows(image):
    """4-bit coverage, two pixels per byte (left pixel in the high nibble)."""
    rows = []
    for y in range(CELL_H):
        row = []
        for x in range(0, CELL_W, 2):
            left = (image.getpixel((x, y)) + 8) // 17
            right = (image.getpixel((x + 1, y)) + 8) // 17
            row.append(left << 4 | right)
        rows.append(row)
    return rows


def text_glyph(font, baseline, character):
    """Drawn SUPERSAMPLE times larger and narrower by STRETCH, then boxed down."""
    s = SUPERSAMPLE
    width = round(CELL_W * s / STRETCH)
    big = Image.new("L", (width, CELL_H * s), 0)
    advance = font.getlength(character)
    ImageDraw.Draw(big).text(((width - advance) / 2, baseline * s), character, fill=255,
                             font=font, anchor="ls")
    return big.resize((CELL_W, CELL_H), Image.Resampling.BOX)


def polygon_glyph(points):
    """A filled polygon in a 6x8-unit cell (the 5x7 font's grid), smoothed."""
    s = SUPERSAMPLE
    big = Image.new("L", (CELL_W * s, CELL_H * s), 0)
    unit_x = CELL_W * s / 6
    unit_y = CELL_H * s / 8
    ImageDraw.Draw(big).polygon([(x * unit_x, y * unit_y) for x, y in points], fill=255)
    return big.resize((CELL_W, CELL_H), Image.Resampling.BOX)


def main():
    font_path, output_path = sys.argv[1], sys.argv[2]
    font = ImageFont.truetype(font_path, FONT_PX * SUPERSAMPLE)
    # Center the band from the highest to the lowest ink in the 39 usable rows.
    boxes = [font.getbbox(chr(code), anchor="ls") for code in range(0x21, 0x7F)]
    top = min(box[1] for box in boxes) / SUPERSAMPLE
    bottom = max(box[3] for box in boxes) / SUPERSAMPLE
    baseline = (GLYPH_H - (bottom - top)) / 2 - top

    glyphs = [(repr(chr(code)), text_glyph(font, baseline, chr(code)))
              for code in range(0x20, 0x7F)]
    # The same shapes as the 5x7 font's arrows, in its 6x8 grid.
    glyphs.append(("up arrow", polygon_glyph([(0.5, 6), (2.5, 1.2), (4.5, 6)])))
    glyphs.append(("down arrow", polygon_glyph([(0.5, 1.2), (2.5, 6), (4.5, 1.2)])))
    glyphs.append(("backspace", polygon_glyph(
        [(0.3, 3.6), (2.3, 1.6), (2.3, 3.0), (4.8, 3.0), (4.8, 4.2), (2.3, 4.2), (2.3, 5.6)])))

    for name, image in glyphs:
        # Nothing may reach the separator row.
        for x in range(CELL_W):
            image.putpixel((x, CELL_H - 1), 0)

    with open(output_path, "w", newline="\n") as out:
        out.write("/* Generated by tools/make_smooth_font.py from DejaVu Sans Mono Bold "
                  f"at {FONT_PX} px:\n")
        out.write(f"   {len(glyphs)} glyphs of {CELL_W}x{CELL_H} pixels, 4-bit coverage, "
                  "two pixels per byte\n   (left in the high nibble). Do not edit. "
                  "License: fonts/DejaVu-LICENSE.txt. */\n")
        for name, image in glyphs:
            out.write(f"/* {name} */\n{{\n")
            for row in coverage_rows(image):
                out.write("    {" + ", ".join(f"0x{b:02X}" for b in row) + "},\n")
            out.write("},\n")


if __name__ == "__main__":
    main()
